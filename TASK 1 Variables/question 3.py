# Storing the values
Principal_Amount = 10000     # Principal amount
Rate_of_interest = 9         # Rate of interest in %
Time = 3                     # Time in years

# Simple Interest formula: SI = (P × R × T) / 100
simple_interest = (Principal_Amount * Rate_of_interest * Time) / 100

print("Your Principal Amount:-", Principal_Amount)
print("Rate of interest:-     ", Rate_of_interest, "%")
print("Loan Tenure:-          ", Time, "Year")
print("Simple Interest:-      ", simple_interest)
